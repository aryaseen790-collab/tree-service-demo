// Downloads real photos listed in src/data/images.json, resizes them to every
// width the site uses, converts to WebP and rewrites CREDITS.md.
// Usage: fill in sourceUrl / sourcePage / photographer / license for a slot, then
//   npm run images
// Slots with an empty sourceUrl keep their generated illustration.
import sharp from 'sharp';
import { readFileSync, writeFileSync } from 'node:fs';

const manifestUrl = new URL('../src/data/images.json', import.meta.url);
const outDir = new URL('../public/images/', import.meta.url);
const manifest = JSON.parse(readFileSync(manifestUrl, 'utf8'));

let fetched = 0;
for (const slot of manifest.images) {
  if (!slot.sourceUrl) continue;
  if (!slot.photographer || !slot.license || !slot.sourcePage) {
    console.warn(`! ${slot.id}: add photographer, license and sourcePage before using this photo. Skipped.`);
    continue;
  }
  process.stdout.write(`Downloading ${slot.id}... `);
  const res = await fetch(slot.sourceUrl, { redirect: 'follow' });
  if (!res.ok) { console.log(`failed (${res.status})`); process.exitCode = 1; continue; }
  const input = Buffer.from(await res.arrayBuffer());
  for (const w of slot.widths) {
    const h = Math.round((w * slot.height) / slot.width);
    await sharp(input).rotate().resize(w, h, { fit: 'cover', position: 'attention' }).webp({ quality: 72 })
      .toFile(new URL(`${slot.id}-${w}.webp`, outDir).pathname);
  }
  fetched++;
  console.log('done');
}

const rows = manifest.images.map((s) =>
  s.sourceUrl && s.photographer
    ? `| \`${s.id}\` | ${s.alt} | Photo by ${s.photographer} | [source](${s.sourcePage}) | ${s.license} |`
    : `| \`${s.id}\` | ${s.alt} | Original illustration generated by \`scripts/make-placeholders.mjs\` | n/a | Project-owned, free to use |`,
);
writeFileSync(new URL('../CREDITS.md', import.meta.url), `# Image credits

Every image on the site is listed here. This file is generated by \`npm run images\`
from \`src/data/images.json\`. Edit that file, not this one.

| Slot | Alt text | Creator | Source | License |
| --- | --- | --- | --- | --- |
${rows.join('\n')}

Also generated by \`scripts/make-placeholders.mjs\` (project-owned): \`og-default.jpg\`,
\`favicon.svg\`, \`favicon.ico\`, \`apple-touch-icon.png\`, \`icon-192.png\`, \`icon-512.png\`.

## Why illustrations?

The demo ships with original illustrations because stock photo sites could not be
reached from the build environment. To switch to real photos:

1. Find a free-license photo on [Unsplash](https://unsplash.com/license) or
   [Pexels](https://www.pexels.com/license/). Each slot in \`images.json\` has a
   suggested search link.
2. Paste the direct image URL into \`sourceUrl\`, plus \`sourcePage\`,
   \`photographer\` and \`license\` (e.g. "Unsplash License").
3. Run \`npm run images\`. Photos are resized, converted to WebP and this file is updated.

Unsplash and Pexels licenses allow free commercial use without permission, but
neither allows selling unaltered copies or implying endorsement. For the live
site, real photos of the owner's crew and jobs beat stock photos every time.
`);
console.log(`\n${fetched} photo(s) updated. CREDITS.md rewritten.`);
